"""Render the configured Holos/RVC voice once; embed offline charging/shake PCM."""
from pathlib import Path
import hashlib
import json
import os
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
SERVER = ROOT / "BendeRadio/examples/BenderRealtime/local_server"
OUT = ROOT / "artifacts/event-replies"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for key, value in {"RVC_ENABLE": "1", "RVC_PITCH": "-3", "RVC_INDEX_RATE": "0.55",
                       "RVC_RMS": "0.75", "RVC_PROTECT": "0.33",
                       "RVC_PTH": "voice_clone/models/bender.pth",
                       "RVC_INDEX": "voice_clone/models/bender.index",
                       "STANZA_RESOURCES_DIR": "A:/stanza_resources"}.items():
        os.environ.setdefault(key, value)
    sys.path.insert(0, str(SERVER))
    import server
    from event_reactions import EventReactions
    import numpy as np
    logs = []
    server.log = lambda message: logs.append(str(message))
    phrases = [(f"{event}_{i}", event, text)
               for event in ("charging", "shake")
               for i, text in enumerate(EventReactions.REPLIES[event])]
    try:
        server.load_stress_words()
        server.load_uk_stress()
        server.load_holos()
        if server.holos_voice is None:
            raise RuntimeError("Configured Holos voice unavailable")
        print(f"Voice: {server.HOLOS_SPEAKER}, {server.HOLOS_DELIVERY}, speed={server.HOLOS_SPEED}", flush=True)
        header = ["// Generated by agent-tools/build_event_replies.py; PCM16 LE 24k mono.",
                  "#pragma once", "#include <cstddef>", "#include <cstdint>",
                  "namespace EventReplyAudio {", "struct Clip { const uint8_t* data; size_t bytes; };",
                  "constexpr size_t chargingCount = 3, shakeCount = 2;"]
        manifest, total = [], 0
        for name, event, text in phrases:
            logs.clear()
            pcm = server.synth(text)
            samples = np.frombuffer(pcm, dtype=np.int16).astype(np.int32)
            if not samples.size or np.max(np.abs(samples)) < 200:
                raise RuntimeError(f"Silent clip: {name}")
            if "RVC ok" not in logs or any("fallback" in log.lower() or "RVC fail" in log for log in logs):
                raise RuntimeError(f"Voice conversion failed: {name}")
            if len(pcm) >= 500000:
                raise RuntimeError(f"Clip too long for ring: {name}")
            with wave.open(str(OUT / (name + '.wav')), 'wb') as wav:
                wav.setparams((1, 2, 24000, 0, 'NONE', 'not compressed'))
                wav.writeframes(pcm)
            header.append(f"alignas(4) static const uint8_t {name}[] = {{")
            header.extend(','.join(str(v) for v in pcm[i:i+32]) + ',' for i in range(0,len(pcm),32))
            header.append('};')
            total += len(pcm)
            manifest.append(dict(name=name, event=event, text=text, bytes=len(pcm),
                                 seconds=len(pcm)/48000, sha256=hashlib.sha256(pcm).hexdigest()))
            print(f"{name}: {len(pcm)/48000:.2f}s", flush=True)
        if total > 1100000:
            raise RuntimeError(f"Clips exceed firmware flash budget: {total}")
        header.append('static const Clip clips[] = {')
        header.extend(f'{{{name}, sizeof({name})}},' for name, _, _ in phrases)
        header.extend(['};', '}'])
        (ROOT/'BendeRadio/EventReplyAudio.h').write_text('\n'.join(header)+'\n', encoding='utf-8')
        (OUT/'manifest.json').write_text(json.dumps(dict(bytes=total, clips=manifest), ensure_ascii=False, indent=2), encoding='utf-8')
        print(f"Embedded {total} bytes", flush=True)
    finally:
        for module in (server.rvc_convert, server.stress_convert):
            proc = module._proc
            if proc is not None:
                try:
                    proc.communicate('{"cmd":"quit"}\n', timeout=5)
                except Exception:
                    proc.kill()
                    proc.wait(timeout=5)


if __name__ == '__main__':
    main()
