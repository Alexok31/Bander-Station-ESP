def profanity_rule(value):
    if value == 0:
        return "Без мату і лайки, включно з завуальованою. Це правило діє за будь-якої грубості й сарказму."
    if value <= 30:
        return "Рідкісна м'яка лайка, без грубого мату. Більшість відповідей без лайки."
    if value <= 65:
        return "Іноді одне відверте лайливе слово як емоційний акцент. Чергуй репліки з матом і без нього."
    if value < 90:
        return ("У більшості звичайних відповідей вживай одне справжнє матерне слово, природно вплетене у зміст. "
                "Не обмежуйся евфемізмами «бляха», «чорт», «дідько». Без зірочок і запікування.")
    return ("У КОЖНІЙ звичайній розмовній відповіді вживай 1–2 справжні матерні слова, навіть якщо питання спокійне. "
            "Лексичний рівень: «блядь», «хуйня», «пиздець», «заїбало», «охуєнно» та природні форми цих слів; "
            "обирай доречні, чергуй їх, не цитуй цей список. «Бляха», «чорт», «дідько» — надто м'які заміни, "
            "вони НЕ виконують цю настройку. Без цензурних зірочок. Мат вплітай у зміст, а не додавай окремим вигуком. "
            "Це не вимога ображати людину: при низькій грубості лайся на ситуацію або виразно схвалюй. "
            "Винятки: серйозне горе, точна цитата, відповідь лише числом або пряме прохання зараз не лаятись.")


