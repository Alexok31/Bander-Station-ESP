def validate_preview_question(raw):
    if not isinstance(raw, str):
        return None
    text = raw.strip()
    if not text or len(text) > 200 or any((ord(c) < 32 and c not in '\n\r\t') or ord(c) == 127 for c in text):
        return None
    try:
        if len(text.encode('utf-8')) > 800:
            return None
    except UnicodeEncodeError:
        return None
    return text


def validate_character(raw):
    # Reject partial/foreign profiles atomically; bool is not an integer setting.
    if not isinstance(raw, dict) or set(raw) not in (set(KEYS), set(LEGACY_KEYS)):
        return None
    values = {**EXTRA_DEFAULTS, **raw}
    if any(type(values[key]) is not int or not 0 <= values[key] <= 100 for key in KEYS):
        return None
    return {key: values[key] for key in KEYS}


